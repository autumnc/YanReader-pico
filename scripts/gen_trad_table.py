#!/usr/bin/env python3
"""生成 main/ime/trad_table.h 的繁体字形位图。

判定标准: 对 U+346E-U+9FD3 的每个码位做 OpenCC t2s 单字转换, 结果与原文不同
即视为繁体字形。不要改用 TSCharacters 的全部 key —— 像/俱/么/沈/藉/覆/瞭
等字繁简同形, 把它们也算作繁体, 会让简体模式把"图像/俱乐部/为什么/沈阳/
藉此/颠覆/瞭望"这类正常词组一起藏掉。
"""
import argparse
from pathlib import Path

import opencc

LO, HI = 0x346E, 0x9FD3
BYTES = (HI - LO + 8) // 8


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default="main/ime/trad_table.h")
    args = ap.parse_args()

    cc = opencc.OpenCC("t2s")
    bitmap = bytearray(BYTES)
    marked = 0
    for cp in range(LO, HI + 1):
        if cc.convert(chr(cp)) != chr(cp):
            i = cp - LO
            bitmap[i >> 3] |= 1 << (i & 7)
            marked += 1

    lines = []
    for start in range(0, BYTES, 12):
        chunk = bitmap[start:start + 12]
        body = ", ".join(f"0x{b:02x}" for b in chunk)
        lines.append(f"    {body},")

    text = f"""// Auto-generated by scripts/gen_trad_table.py from OpenCC t2s
// 繁体字形位图: U+{LO:04X} - U+{HI:04X}, {BYTES} bytes, {marked} 字
#pragma once
#include <cstdint>
static const uint32_t kTradLo = 0x{LO:04X};
static const uint32_t kTradHi = 0x{HI:04X};
static const uint8_t kTradBitmap[{BYTES}] = {{
{chr(10).join(lines)}
}};
inline bool imeIsTradChar(uint32_t cp) {{
    if (cp < kTradLo || cp > kTradHi) return false;
    uint32_t i = cp - kTradLo;
    return (kTradBitmap[i >> 3] >> (i & 7)) & 1u;
}}
"""
    Path(args.out).write_text(text, encoding="utf-8")
    print(f"{args.out}: {BYTES} bytes, {marked} 繁体字形")


if __name__ == "__main__":
    main()
