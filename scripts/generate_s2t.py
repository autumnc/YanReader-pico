# 去重（dict 本身唯一）并按键码点升序
items = sorted(S2T.items(), key=lambda kv: ord(kv[0]))

# 校验：键必须都是单 BMP 字，值 UTF-8 非空
for s, t in items:
    assert len(s) == 1 and 0x4E00 <= ord(s) <= 0x9FFF, f"bad key {s!r}"
    assert t, f"empty trad for {s!r}"


def hdr():
    return (
        "/* 由 scripts/generate_s2t.py 生成 — 勿手改。简→繁单字映射，按码点升序。 */\n"
        "#pragma once\n"
        "#include <stdint.h>\n\n"
        "typedef struct { uint16_t s; const char* t; } s2t_entry_t;\n\n"
    )


def body():
    lines = []
    lines.append(f"static const s2t_entry_t S2T_TABLE[{len(items)}] = {{")
    for s, t in items:
        lines.append(f"    {{ 0x{ord(s):04X}, \"{t}\" }},")
    lines.append("};")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    out = sys.argv[1] if len(sys.argv) > 1 else "main/ime/s2t_table.h"
    with open(out, "w", encoding="utf-8") as f:
        f.write(hdr())
        f.write(body())
    print(f"{len(items)} entries -> {out}")
