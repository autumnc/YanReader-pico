#pragma once

#include <stdint.h>

// Read Pico 输入适配：3 电容键（触摸条下方）+ 触摸手势 + PMU 电源键 → pjournal 键码。
// 语义对齐原 GPIO 物理键：USER(上移/长按蓝牙/双击语音)、BOOT(下移/长按休眠)。

enum PicoKey {
    PICO_KEY_USER = 0,   // 电容键 KEY1
    PICO_KEY_BOOT = 1,   // 电容键 KEY2
};

void input_init();

// 物理键当前是否按下（消抖后）。主循环用它替代原 PIN_LOW 轮询。
bool input_key_held(int key);

// 最近一次显示区点按的逻辑坐标；无未消费点按时返回 false。读后清除。
// 主界面用它做图标点选：命中哪个图标槽位就激活哪个。
bool input_tap_xy(int *x, int *y);

// 同 input_tap_xy，但**不消费**：读一眼有没有点按、落在哪，留着给调用方稍后再取。
// 给"先判断这次点按归不归自己"的场景用（浮层/软键盘先看落点是否在自己的矩形里，
// 不在就原样让给下层去 input_tap_xy）——输入层没有"取回"接口，只能不取。
bool input_tap_peek_xy(int *x, int *y);

// 最近一次触摸手势的**按下点**（逻辑坐标，任何手势抬手都有：点按/长按/上下滑/左右滑）；
// 无未消费值时返回 false。读后清除。
// 和 input_tap_xy 的区别只在"滑动"这一种：滑动抬手产生的是翻页键/左右键，不是 '\n'，
// 所以它不带坐标——但"这次滑动是从屏幕哪一块开始的"只能靠按下点判断（虚拟键盘候选行
// 左右划翻页：起点落在候选行才算翻候选，落在正文上仍是翻页/移光标）。
// 只在"产生这个按键的那一帧"有效：input_poll() 每帧开头会清掉，不会把上一次手势的
// 按下点留给后来某个 BLE 键盘的左右键。
bool input_press_xy(int *x, int *y);

// 最近一次触摸拖动的位移增量（逻辑像素，正 y = 手指下移），随 KEY_TOUCH_DRAG
// 一起到达；无未消费增量时返回 false。读后清除。增量是"相对上一次拖动上报"的，
// 不是相对按下点，所以漏掉几帧也只丢中间过程、不丢总位移。
bool input_drag_xy(int *dx, int *dy);

// 伴随 KEY_BACK 的方向：+1 = 手指左滑（内容右移，同 KEY_RIGHT 约定），-1 = 手指右滑。
// 无未消费值时返回 false。读后清除。和 input_press_xy() 一样只对产生它的那一帧有效。
// 用途：虚拟键盘候选行左右划翻页（editorVkSwipePage 的第三个参数就是它）。
bool input_back_dir(int *dir);

// 每帧轮询一次（与 g_bt.readKey() 互补）：返回 pjournal 键码或 0。
// 覆盖：电容键 KEY3(确认)、显示区触摸手势(点按/上下滑/左右滑)、电源键短按。
int input_poll();

// 「刚刚是**因为电源键**才从待机唤醒的」。下一次 PMU 短按事件若落在一个很短的窗口里，
// 就认定它是"唤醒那一按的抬手"直接吞掉，不上报 KEY_POWER。
// 待机时按电源键只该把设备叫醒，不该顺带把模式转一圈：唤醒那一按 =
// KEY_DOWN（key wake，read_pico_pmu_take_key_wakeup 已经 ack 掉）+ 松手时的 KEY_SHORT，
// 后者是睡着之后才进队列的，没人能代表它说"这是唤醒那一按"。所以由 enterLightSleep
// 在判明真按键唤醒之后**主动登记一次**，剩下的交给时间窗（见 input.cpp）。
void input_note_key_wake();

// 长阻塞段（整屏重绘 + 刷屏约 110ms）内插入的补充采样点。
// 主循环只在空闲时每 50ms 采一次触摸，而一次重绘加刷屏就有约 110ms 完全不采样，
// 期间开始又结束的快速点按两次采样都看不到——用户侧就是"按了好几次没反应"。
// 在阻塞段里调它补采，产生的按键暂存，下一次 input_poll() 返回。
// **当前无调用点**：刷屏已搬去 core1（ui_render.cpp），主循环不再被按住几百毫秒，
// 触摸每轮 input_poll() 采一次就够。保留实现备用（cst836u 不是线程安全的，
// 任何时候都只能在主循环那个任务里调，绝不能在渲染任务里调）。
// 只能在主循环所在的同一个任务里调用（触摸驱动不是线程安全的）。
void input_tick();

// 长阻塞段里问一句"用户已经在按下一个键了吗"：补采一次触摸，返回暂存的待发按键
// （0 = 没有）。**不消费**——下一次 input_poll() 照样把它取走。
// 供图像解码这类长循环判断"该收手了"：解码期间主循环完全不采样，而 cst836u 只返回
// "当前"按下状态（没有锁存），一次快速滑动手势会整个落在解码窗口里被丢掉，用户侧
// 就是"划了没反应"。只会看到触摸手势产生的键，BLE 键盘的键要 readKey() 才看得到
// （那会消费掉，这里不做）。同样只能在主循环那个任务里调。
int input_pending_key();
