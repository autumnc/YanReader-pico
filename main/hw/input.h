#pragma once

#include <stdint.h>

// Read Pico 输入适配：3 电容键（触摸条下方）+ 触摸手势 + PMU 电源键 → pjournal 键码。
// 语义对齐原 GPIO 物理键：USER(上移/长按蓝牙/双击语音)、BOOT(下移/长按休眠)。

enum PicoKey {
    PICO_KEY_USER = 0,   // 电容键 KEY1
    PICO_KEY_BOOT = 1,   // 电容键 KEY2
};

void input_init();

// 物理键当前是否按下（消抖后）。主循环用它替代原 PIN_LOW 轮询。
bool input_key_held(int key);

// 最近一次显示区点按的逻辑坐标；无未消费点按时返回 false。读后清除。
// 主界面用它做图标点选：命中哪个图标槽位就激活哪个。
bool input_tap_xy(int *x, int *y);

// 同 input_tap_xy，但**不消费**：读一眼有没有点按、落在哪，留着给调用方稍后再取。
// 给"先判断这次点按归不归自己"的场景用（浮层/软键盘先看落点是否在自己的矩形里，
// 不在就原样让给下层去 input_tap_xy）——输入层没有"取回"接口，只能不取。
bool input_tap_peek_xy(int *x, int *y);

// 同 input_tap_peek_xy，但看的是**已经排队、还没被 input_poll() 取走**的那一个键的
// 点按落点（阅读器整条绘制+推屏都在主循环任务里同步跑，这期间采到的键只能排队）。
// 不消费也不影响它稍后被正常取走。无待发键、待发的那一个不是点按（滑动/电容键/长按
// 之外的按键）时返回 false。
// 用途：阅读器推屏后那段空档想问一句"等着的那一指是不是朝我这一侧的翻页"——决定
// 要不要把手上的预渲染干完（见 screen_reader.cpp 的 rdPendingTurnDir）。
bool input_pending_tap_xy(int *x, int *y);

// 最近一次触摸手势的**按下点**（逻辑坐标，任何手势抬手都有：点按/长按/上下滑/左右滑）；
// 无未消费值时返回 false。读后清除。
// 和 input_tap_xy 的区别只在"滑动"这一种：滑动抬手产生的是翻页键/左右键，不是 '\n'，
// 所以它不带坐标——但"这次滑动是从屏幕哪一块开始的"只能靠按下点判断（虚拟键盘候选行
// 左右划翻页：起点落在候选行才算翻候选，落在正文上仍是翻页/移光标）。
// 只在"产生这个按键的那一帧"有效：input_poll() 每帧开头会清掉，不会把上一次手势的
// 按下点留给后来某个 BLE 键盘的左右键。
bool input_press_xy(int *x, int *y);

// ── 长阻塞段补采样：按时间设闸的 input_tick ────────────────────────────────
// 一次要跑几十上百毫秒、中间没人会去采触摸的活，每次迭代调一次这个（不是 input_tick：
// 每次都真读 I2C 太贵）。它 12ms 放行一次，把那一段切成 ≤12ms 的碎片。
//
// 为什么必须有：cst836u 没有锁存寄存器，一次点按要成立，必须有一拍采样落在手指按住的
// 那段时间里（按住 p50 107ms）。任何 ≥100ms 的零采样段都会**整次吞掉**落在里面的点按。
// 实测两个这样的段：整块键盘重绘（50ms，见 editor_vk.cpp 的 evkKey）和词库整表落盘
// （124~187ms，每 8.5s 一次，见 IME.cpp 的 saveUserDictFile 写循环）—— 后者是漏键的
// 主因，它把"打字期最长采样间隔"顶到 155~250ms，正好等于它自己的时长。
//
// 不放在 input.cpp 里自己找地方调：长活分散在几个模块（绘制、词库落盘），得由长活的
// 主人自己在循环里喊一声 —— 只有它知道哪一段是能安全喘气的。
void input_tick_throttled();

// ── 按下沿（步 5「按下即反馈」用）────────────────────────────────────────
// "手指刚落到屏上"的那一拍，逻辑像素坐标。**消费式**：读一次就没了，同一拍不给第二次。
//
// 为什么不能拿现有的：`input_press_xy` 要等抬手那帧才有值，`s_press_origin_valid`
// 只在拖动/长按/抬手时才置位 —— 而按下反馈要的恰恰是"按下去"这一拍。点按是在**抬手**
// 那一帧才变成 '\n' 的（见本文件的手势状态机），手指落屏 p50 107ms 之后才抬手；
// 早了这 107ms 把键帽反白，用户看到的"点下去→屏开始变"就从抬手后提前到落屏后一拍内。
bool input_press_edge_xy(int *x, int *y);

// 按下沿的**序号**，每来一次按下沿 +1。给"同一个按下只响一声"这类判断用：抬手那头
// 拿它比对，就知道这一声是不是已经在按下沿响过了（见 screen_editor 的按键音）。
// 比"布一个 bool 再找地方清"可靠 —— 按下去又拖出键盘再抬手的那一路永远不会走到
// 任何清标志的地方，标志就会留在那儿把**下一个**键的声音吃掉。
uint32_t input_press_seq();

// 扔掉一个还没被读走的按下沿。给"这一拍是按键回合"的入口用（见 screen_editor_handle
// 开头）：长绘制段里补采样（见 editor_vk.cpp 的 evkKey）会在**屏幕正在重画**的时候
// 记下按下沿，而那次点按的抬手马上也在同一段里被采到、当场变成一个键投递出去。等这一拍
// 结束回到空转循环，那个按下沿已经是**上一件事的残影** —— 照常读它就会给一个早就上屏的
// 字补一帧反白键帽，而且这一帧没人再擦（空转不重画），一直挂到下一次按键。
void input_press_edge_discard();

// 丢掉排队中的待发键（换屏时调，见 main.cpp 派发之后）。理由见 .cpp 的说明。
void input_flush_pending();

// 最近一次触摸拖动的位移增量（逻辑像素，正 y = 手指下移），随 KEY_TOUCH_DRAG
// 一起到达；无未消费增量时返回 false。读后清除。增量是"相对上一次拖动上报"的，
// 不是相对按下点，所以漏掉几帧也只丢中间过程、不丢总位移。
bool input_drag_xy(int *dx, int *dy);

// 伴随 KEY_BACK 的方向：+1 = 手指左滑（内容右移，同 KEY_RIGHT 约定），-1 = 手指右滑。
// 无未消费值时返回 false。读后清除。和 input_press_xy() 一样只对产生它的那一帧有效。
// 用途：虚拟键盘候选行左右划翻页（editorVkSwipePage 的第三个参数就是它）。
bool input_back_dir(int *dir);

// 每帧轮询一次（与 g_bt.readKey() 互补）：返回 pjournal 键码或 0。
// 覆盖：电容键 KEY3(确认)、显示区触摸手势(点按/上下滑/左右滑)、电源键短按。
int input_poll();

// 「刚刚是**因为电源键**才从待机唤醒的」。下一次 PMU 短按事件若落在一个很短的窗口里，
// 就认定它是"唤醒那一按的抬手"直接吞掉，不上报 KEY_POWER。
// 待机时按电源键只该把设备叫醒，不该顺带把模式转一圈：唤醒那一按 =
// KEY_DOWN（key wake，read_pico_pmu_take_key_wakeup 已经 ack 掉）+ 松手时的 KEY_SHORT，
// 后者是睡着之后才进队列的，没人能代表它说"这是唤醒那一按"。所以由 enterLightSleep
// 在判明真按键唤醒之后**主动登记一次**，剩下的交给时间窗（见 input.cpp）。
void input_note_key_wake();

// 长阻塞段（整屏重绘 + 刷屏约 110ms）内插入的补充采样点。
// 主循环只在空闲时每 50ms 采一次触摸，而一次重绘加刷屏就有约 110ms 完全不采样，
// 期间开始又结束的快速点按两次采样都看不到——用户侧就是"按了好几次没反应"。
// 在阻塞段里调它补采，产生的按键暂存，下一次 input_poll() 返回。
// **刷屏搬去 core1（ui_render.cpp）之后**，界面这条路的阻塞段没了，但**阅读器是例外**：
// 它整条绘制 + 推屏都在主循环那个任务里同步跑，一帧翻页要按住约 2s。所以它那边
// （screen_reader.cpp 的 renderCurrent，推屏之前）仍在调这个补采点。编辑器空转那段
// （main.cpp:484）也在调。
// cst836u 不是线程安全的：任何时候都只能在主循环那个任务里调，绝不能在渲染任务里调。
void input_tick();

// 长阻塞段里问一句"用户已经在按下一个键了吗"：补采一次触摸，返回暂存的待发按键
// （0 = 没有）。**不消费**——下一次 input_poll() 照样把它取走。
// 供图像解码这类长循环判断"该收手了"：解码期间主循环完全不采样，而 cst836u 只返回
// "当前"按下状态（没有锁存），一次快速滑动手势会整个落在解码窗口里被丢掉，用户侧
// 就是"划了没反应"。只会看到触摸手势产生的键，BLE 键盘的键要 readKey() 才看得到
// （那会消费掉，这里不做）。同样只能在主循环那个任务里调。
int input_pending_key();
