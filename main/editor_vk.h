#pragma once

#include <string>

// 写作模式虚拟键盘：未连接蓝牙键盘时显示，直接接系统拼音输入法(IME)。
//
// 交互语义与阅读器的 VK(screen_reader.cpp)一致，但绘制不能复用：阅读器走
// GfxRenderer，编辑器的正文/状态栏走 u8g2 shim + g_font，两条渲染栈的坐标
// 映射不同。这里重写绘制，交互(键表/命中/喂 IME)保持同构。
//
// 核心思路：命中测试把点按**翻译成普通键码**，交给 screen_editor_handle 既有的
// IME 分支 / 回车 / 退格 / ASCII 插入逻辑处理——不重复实现任何输入逻辑。

// 命中测试返回的特殊键码。普通键直接返回字符码('a'..'z'、' '、'\b'、'\n'、
// 符号页的标点与数字)；EVK_NONE(0) 表示点在键盘空白处，调用方应吞掉本次点按。
//
// 面板自上而下：候选区(上行编码 / 下行候选) + 额外行 + 键区 + 功能行。
// 键区有三张面：字母页（qwerty 或一键多字母布局）、**符号面板**、**数字面板**，
// 由功能行最左那两个键切换（见 EditorVkKey::EVK_PAGE）。符号/数字面板都是一张
// 独立的键表，照手机输入法那两张来：符号面板是 10 列 × 3 行的标点表（不含数字），
// 数字面板是 左列#*-+ | 中间 1..9 与宽 0 | 右列⌫ . @ / 的四行数字盘。
// 组合中点上行的编码行 → 候选区之下整块换成 T9 面板（左列挑读音、右面候选宫格），
// 见 .cpp 的 evkT9*；再点一次编码行收起，组合结束也会自动收起。面板里上下滑滚：
// 左列滚读音行（放不下时）、宫格翻候选页——见 editorVkSwipeScroll。
// 额外行是「布局 | Ctl | ◀ ▲ ▼ ▶ | Shift | ⌫」，横竖屏一致。四个方向键返回
// KEY_LEFT/UP/DOWN/RIGHT(0x80~0x83)：输入法有编码时它用来选字翻页(IME 内部
// 已把 ↑↓ 映射为候选翻页)，无编码时 IME 直接放行，编辑器用它移动光标。
// Shift/⌫ 是图形键帽(字体子集里没有 ⇧ 和退格箭头的码点，走 icon_font 直接画)。
// 一键多字母布局（14/18/9 键）只在中文拼音态生效：英文/未开输入法一律回到 26 键，
// 那时组标签没有意义。
// 每一类都只是把点按翻译成普通键码或待发状态，不新增输入逻辑。
enum EditorVkKey {
    EVK_NONE = 0,
    EVK_PAGE = -1,   // 换面板（字母 / 符号 / 数字 三张面）：命中测试内已切好，调用方整块重绘即可
    EVK_LANG = -2,   // 中/英：未开输入法→开中文；已开→拼音/英文切换
    EVK_CTRL = -3,   // Ctrl 组合键：命中测试内已翻转待发状态，调用方重绘即可
    EVK_SHIFT = -4,  // Shift 待发：同上，下一个字母转大写后自动清除
    EVK_LAYOUT = -5, // 键位布局循环 26→14→18→9：命中测试内已翻转并写设置，调用方重绘即可
    EVK_T9 = -6,     // 开/关 T9 候选面板（点候选区上行的编码行），或面板里换了读音：
                     // 命中测试内已翻转/已重建候选，调用方整块重画(建议全刷)即可
    EVK_SEP = -7,    // 九宫格「1 分词」：命中测试内已确定下一个音节、候选已重算，
                     // 调用方重绘候选区即可（只在 9 键布局里有这个键）
    EVK_CLEAR = -8,  // 九宫格「重输」：命中测试内已清空当前拼音组合，调用方重绘即可
    EVK_NOOP = -9,   // 命中测试内**故意什么都不做**（九宫格组合中的「0」）。
                     // 和 EVK_NONE 的区别：那个是"点在死区、连按下反馈都不该有"，
                     // 这个是"键确实被按到了，只是此刻没有动作"，调用方照常重绘，
                     // 让按键反色反馈出去，用户才知道按到了。
};

// 进入编辑器时调用：未连蓝牙键盘则默认显示，并清除手动覆盖标记。
void editorVkInit();
// 蓝牙键盘连上后自动收起。用户手动开关过之后以手动为准，不再自动。
void editorVkSyncBtState();
// 进入"要打字"的界面（新建/重命名/编辑字段/写笔记…）时调用：没连蓝牙键盘就把键盘
// 弹出来，并清掉手动覆盖标记。新一次输入会话应该直接能打字，而不是再点一次状态栏
// 图标。连了蓝牙键盘时保持收起（物理键输入）。
void editorVkAutoShow();

bool editorVkVisible();
void editorVkSetVisible(bool on);

// 候选字在候选行里的像素宽度（按「候选字大小」设置量，不含 "N." 编号前缀）。
// 给输入法分页用：main.cpp 的 setWidthFn 在键盘可见时改调这个，保证"输入法算的一行
// 放几个"和"键盘实际画得下几个"是同一个字号下的结论。
int editorVkCandidateWidth(const char *text);

// 键位布局（26 / 14 / 18 / 9 键）的外部入口：key 是 "26"/"14"/"18"/"9"，与设置项
// "kb_layout" 存的是同一串字面量。设置界面用它切换并持久化；editorVkInit 反过来从
// 设置读。键盘上的"布局"键走的是内部同一条路（点一下就换下一个布局并写设置）。
// 三个一键多字母布局的分组都取自万象拼音，见 IME.cpp 顶部的键位表。
void editorVkSetLayout(const char *key);
const char *editorVkLayoutKey();   // 当前布局的 key（"26"/"14"/"18"/"9"）

// 键盘面板顶边 y。正文区底边应裁到此处(见 drawEditor)。
int editorVkTop();

// 编码区+候选区(面板顶部的两行)的总高。ui_render 用它圈出"上屏时该清一遍"的矩形。
int editorVkCandH();

// 状态栏右侧键盘开关图标槽宽(像素)。返回 0 表示本界面不提供开关。
int editorVkIconSlotW();
bool editorVkIconHit(int x, int y);

// 绘制键盘面板(候选条 + 按键)。调用方须在正文之后、状态栏之前调用。
void editorVkDraw();
// 绘制状态栏开关图标(反白=键盘已展开)。须在 ui_draw_status 之后调用，
// 否则会被状态栏的白色底盖掉。
void editorVkDrawIcon();

// 一次命中的几何描述（可选输出）。命中测试本来就要算出这个键的矩形，把它回带出来，
// 按下反馈就能照同一份几何把键重画成反色，不必再猜一遍。text 用小缓冲而非指针：
// 键帽文字大多来自栈上的临时 char[2]。九宫格的「1 分词」是这里最长的标签（UTF-8 8
// 字节 + 结尾），所以留 16。
struct EditorVkHit {
    int x = 0, y = 0, w = 0, h = 0;
    int shape = 0;        // 0=文字键 1=三角方向键 2=Shift 3=候选 4=退格 5=空格 6=回车
    int dir = 0;          // shape==1：0=左 1=上 2=下 3=右
    char text[16] = {};   // shape==0/3 的键帽文字(shape>=4 是图标键，不看文字)
    bool filled = false;  // 常态就反色（Ctrl/Shift 待发、英文态的中/英键、高亮候选）
};

// 命中测试：返回 EditorVkKey 或普通字符码。hit 非空时回带命中元素的几何。
// 命中判定为"中心优先"：点必须落在键的内切椭圆内，矩形四角是死区（见 .cpp）。
// 一键多字母布局下字母键返回 IME::KEY_AMBIG_BASE + 组号（IME 未开中文输入法时退化
// 为该组首字母），其余键与 26 键布局完全一致。
int editorVkHitTest(int x, int y, EditorVkHit *hit = nullptr);

// 按下反馈：记下命中的键，由 editorVkDraw 在本次重绘的结尾把该键画成反色。
// 不额外推屏——反馈搭按键动作自己那次刷新的顺风车，下一次重绘覆盖即"抬起恢复"。
void editorVkMarkPressed(const EditorVkHit &hit);

// 丢掉按下反馈。给"按下去会改变自己外观"的键用（中/英、布局切换、翻页…）：命中测试
// 回带的几何/文字是按下前的那一份，而这些键的动作本身已经把它重画成新样子了，再叠
// 一层旧标签就会出现两个标签摞在一起（"拼"/"英"叠字，要再按一个别的键才刷新）。
void editorVkClearPressed();

// 候选行左右滑动翻页。x/y 是本次手势的**按下点**（input_press_xy），dir: +1=下一个/后一页
// (手指左划)，-1=前一个/上一页。返回 true = 这次滑动是"划候选"，已经翻页（或没有可翻的
// 页），调用方应该把触发它的那个 KEY_LEFT/RIGHT 吃掉——否则同一划还会顺手把书翻一页 /
// 把光标移一格 / 切一个标签。返回 false = 起点不在候选行，界面照旧处理那个左右键。
// 只在键盘可见时有意义。左右划的方向约定与 input.cpp 的"手指左滑 = 下一个"一致。
bool editorVkSwipePage(int x, int y, int dir);

// T9 候选面板（点开"编码"行后）里的上下滑动，起点决定滚哪一块：
//   左列读音列 → 一次滚一行读音（列里放不下时才有得滚，右侧会画一条滚动条）；
//   候选宫格   → 一次翻一页候选（与候选条上左右划共用 pagePrev/pageNext）。
// dir: +1 = 手指上滑(往后看) / -1 = 手指下滑(往前看)。
// 返回 true = 这一划归面板，调用方必须吃掉触发它的那个上下键——否则同一划还会
// 顺手把正文滚一屏 / 把书翻一页 / 把候选翻一页。面板没展开时返回 false，上下滑
// 照旧是翻页。与 editorVkSwipePage 一样只看起点。
// 触屏竖滑在主循环里已被 main.cpp 从 KEY_PAGE_UP/DOWN 回退成 KEY_UP/DOWN，
// 所以调用方两个键码都要认（阅读页/编辑器都靠 input_press_xy 区分触屏与实体键）。
bool editorVkSwipeScroll(int x, int y, int dir);

// 按像素宽截断 UTF-8 串，给状态栏右侧文字让位给键盘图标用。
std::string editorVkTruncateToWidth(const std::string &s, int maxWidth);

// 界面主动收起键盘（离开"可打字"的子状态时用，比如设置里从词典新增退回词典列表）。
// 与 editorVkSetVisible(false) 的区别：不置 userOverride——那个标记是"用户手动关过，
// 别再自动弹回来"，界面自己收键盘不是用户的意愿，下次 editorVkAutoShow() 还得能弹出来。
void editorVkAutoHide();

// 软键盘点按泵：可打字的子状态里、处理按键之前调用一次。挂起的点按**落在键盘面板上**
// 时把它消费掉、翻译成键码：
//   *outKey      = 要喂给界面的普通键码（0 = 只是重绘：按下反馈/翻页/切布局/切待发修饰键）
//   *outTurnImeOn = true 表示"刚点了中/英，而调用方的输入法原来是关的" → 调用方应把
//                   自己的 IME 打开（g_ime.setActive(true)）。已开着时泵内部已经切了中英。
// 返回 true = 点按归键盘（已消费）；false = 没落在面板上，一个字都没动，调用方照旧
// input_tap_xy() 取它。**不认状态栏上的开关图标**——那个图标要不要画、命中怎么算，
// 由各界面自己决定（编辑器/计划/大纲自己处理）。
bool editorVkPumpTap(bool imeActive, int *outKey, bool *outTurnImeOn);
